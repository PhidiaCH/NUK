print(22 + 28)             # 50
print(150 - 5*26)          # 20
print((150 - 5*26) / 5)    # 4.0  除法一定回傳 float
print(80 / 5)              # 16.0
print(79 // 3)             # 26   floor division
print(79 % 3)              # 1    modulus
print(1.41421 ** 2)        # 1.9999899240999999
print(10 ** 3)             # 1000
